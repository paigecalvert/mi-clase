create policy "Users can manage files for their homework"
on public.homework_files
for all
to authenticated
using (
  exists (
    select 1
    from public.homework
    join public.classes on classes.id = homework.class_id
    where homework.id = homework_files.homework_id
      and classes.user_id = auth.uid()
  )
)
with check (
  exists (
    select 1
    from public.homework
    join public.classes on classes.id = homework.class_id
    where homework.id = homework_files.homework_id
      and classes.user_id = auth.uid()
  )
);

